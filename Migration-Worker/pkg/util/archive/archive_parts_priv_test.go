// buildSplitPart makes a tar containing only a single split entry, simulating one part generated by XDM.
func buildSplitPart(t *testing.T, name string, mode int64, uid, gid int,
	content []byte, offset, total int64, xattrKey, xattrVal string) []byte {

	t.Helper()

	var buf bytes.Buffer
	tw := tar.NewWriter(&buf)

	pax := map[string]string{
		paxSplitOffset: fmt.Sprintf("%d", offset),
		paxSplitTotal:  fmt.Sprintf("%d", total),
	}
	if xattrKey != "" {
		// XDM writes exactly this form; archive/tar auto-fills hdr.Xattrs when reading it back.
		pax["SCHILY.xattr."+xattrKey] = xattrVal
	}

	hdr := &tar.Header{
		Typeflag:   tar.TypeReg,
		Name:       name,
		Size:       int64(len(content)),
		Mode:       mode,
		Uid:        uid,
		Gid:        gid,
		Format:     tar.FormatPAX,
		PAXRecords: pax,
	}
	if err := tw.WriteHeader(hdr); err != nil {
		t.Fatalf("write header: %v", err)
	}
	if _, err := tw.Write(content); err != nil {
		t.Fatalf("write content: %v", err)
	}
	if err := tw.Close(); err != nil {
		t.Fatalf("close tar: %v", err)
	}
	return buf.Bytes()
}

// TestApplySplitFileMetadataPreservesPrivBits covers the C3 fix.
//
// A setuid file is split into 3 ranges written by 3 concurrent workers. The
// kernel's file_remove_privs clears the setuid bit and xattrs on every pwrite,
// so they can only survive by being re-applied once after the barrier. Before
// the fix writeSplitChunk did Chmod then Lchown in place (the order was
// reversed too) and never set xattrs.
func TestApplySplitFileMetadataPreservesPrivBits(t *testing.T) {
	const (
		name     = "big.bin"
		xattrKey = "user.xdmtest" // security.* needs privileges; use user.* to exercise the same code path
		xattrVal = "cap-stand-in"
	)
	content := []byte("0123456789ab") // 12 bytes, split into 3 ranges of 4 bytes each
	total := int64(len(content))
	chunk := int64(4)
	mode := int64(0o4755) // setuid + rwxr-xr-x

	dest := t.TempDir()
	uid, gid := os.Getuid(), os.Getgid()

	// Probe whether the target filesystem supports user.* xattrs; if not, only verify setuid.
	probe := filepath.Join(dest, ".probe")
	if err := os.WriteFile(probe, []byte("x"), 0o600); err != nil {
		t.Fatalf("probe file: %v", err)
	}
	xattrSupported := system.Lsetxattr(probe, xattrKey, []byte("v"), 0) == nil
	os.Remove(probe)
	if !xattrSupported {
		t.Logf("filesystem at %s does not support %s, skipping xattr assertions", dest, xattrKey)
	}

	key := xattrKey
	if !xattrSupported {
		key = ""
	}

	var parts [][]byte
	for off := int64(0); off < total; off += chunk {
		parts = append(parts, buildSplitPart(t, name, mode, uid, gid,
			content[off:off+chunk], off, total, key, xattrVal))
	}

	// N-way concurrent extract, consistent with unpackPartsConcurrently.
	var (
		wg     sync.WaitGroup
		mu     sync.Mutex
		splits []SplitFileInfo
		errs   []error
	)
	for _, p := range parts {
		wg.Add(1)
		go func(raw []byte) {
			defer wg.Done()
			got, err := UnpackPart(context.Background(), bytes.NewReader(raw), dest, &TarOptions{})
			mu.Lock()
			defer mu.Unlock()
			if err != nil {
				errs = append(errs, err)
				return
			}
			splits = append(splits, got...)
		}(p)
	}
	wg.Wait()

	for _, err := range errs {
		t.Fatalf("UnpackPart: %v", err)
	}
	if len(splits) != len(parts) {
		t.Fatalf("collected %d split entries, want %d", len(splits), len(parts))
	}

	target := filepath.Join(dest, name)

	// Before the fix: setuid is already cleared by the last pwrite here.
	if fi, err := os.Stat(target); err != nil {
		t.Fatalf("stat before barrier: %v", err)
	} else if fi.Mode()&os.ModeSetuid != 0 {
		t.Logf("setuid survived the writes on this kernel (mode=%v); "+
			"the barrier fixup is still what guarantees it", fi.Mode())
	}

	if err := ApplySplitFileMetadata(splits); err != nil {
		t.Fatalf("ApplySplitFileMetadata: %v", err)
	}

	// 1) content complete
	got, err := os.ReadFile(target)
	if err != nil {
		t.Fatalf("read target: %v", err)
	}
	if !bytes.Equal(got, content) {
		t.Errorf("content = %q, want %q", got, content)
	}

	// 2) the setuid bit survived - this is the core of the fix
	fi, err := os.Stat(target)
	if err != nil {
		t.Fatalf("stat after barrier: %v", err)
	}
	if fi.Mode()&os.ModeSetuid == 0 {
		t.Errorf("setuid bit lost, mode = %v (want it set)", fi.Mode())
	}
	if perm := fi.Mode().Perm(); perm != 0o755 {
		t.Errorf("perm = %#o, want 0755", perm)
	}

	// 3) xattr landed - before the fix this was always empty
	if xattrSupported {
		v, err := system.Lgetxattr(target, xattrKey)
		if err != nil {
			t.Fatalf("Lgetxattr(%s): %v", xattrKey, err)
		}
		if string(v) != xattrVal {
			t.Errorf("xattr %s = %q, want %q", xattrKey, v, xattrVal)
		}
	}
}

// TestApplySplitFileMetadataDetectsTruncation confirms the length check is not broken by changes.
func TestApplySplitFileMetadataDetectsTruncation(t *testing.T) {
	dest := t.TempDir()
	uid, gid := os.Getuid(), os.Getgid()

	// Provide only range 1 of 3 and declare total length 12: must error.
	raw := buildSplitPart(t, "big.bin", 0o644, uid, gid, []byte("0123"), 0, 12, "", "")

	splits, err := UnpackPart(context.Background(), bytes.NewReader(raw), dest, &TarOptions{})
	if err != nil {
		t.Fatalf("UnpackPart: %v", err)
	}
	if err := ApplySplitFileMetadata(splits); err == nil {
		t.Fatal("expected a truncation error, got nil")
	}
}
