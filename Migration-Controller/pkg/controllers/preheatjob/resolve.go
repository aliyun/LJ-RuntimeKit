const (
	// storageTypeOSS / storageTypeDragonfly are the only two backends that can
	// compose an http(s) origin address; local / nfs have no URL for Dragonfly
	// to fetch from.
	storageTypeOSS       = "oss"
	storageTypeDragonfly = "dragonfly"
	// storageTypePVC: the checkpoint data lives in the user's PVC: the preheat
	// source resolves to the pvc field; remoteURL is generated only by the
	// dragonfly backend after the controller brings up the preheat source pod
	// (http://<Service ClusterIP>:<fixed port>/<path>); the EFC and copy
	// backends do not need it.
	storageTypePVC = "pvc"
)

// resolvedSource is the preheat source resolved from the checkpoint CR. OSS
// source fills remoteURL + credentials; PVC source fills the three pvc fields
// with remoteURL empty (generated only by the caller after bringing up the
// preheat source pod, dragonfly backend only).
type resolvedSource struct {
	remoteURL       string
	accessKeyID     string
	accessKeySecret string

	pvcName      string
	pvcNamespace string
	pvcPath      string

	// checkpointSize is the total size of the checkpoint data
	// (CheckpointAttributes.Size). EFC preheat compares it with the warmup
	// stat's TotalSize to verify data integrity.
	checkpointSize int64
}

// IsPVC reports whether the resolved source is a PVC source.
func (s *resolvedSource) IsPVC() bool {
	return s.pvcName != ""
}

// PVC exports the three pvc fields as a PreheatJobPVC (for callers to build the preheat source pod).
func (s *resolvedSource) PVC() *v1beta1.PreheatJobPVC {
	return &v1beta1.PreheatJobPVC{
		PvcName:      s.pvcName,
		PvcNamespace: s.pvcNamespace,
		PvcPath:      s.pvcPath,
	}
}

// resolveSourceFromCheckpoint finds the checkpoint CR by spec.checkpointUID
// and composes the preheat remoteURL and OSS credentials. The resolved result
// is only used in the caller's in-memory flow for that round and never written
// back to spec; shared by the reconciler and ProbeController.
//
// The composition rule must be exactly identical to the worker-side download,
// otherwise the task_id computed by dfdaemon mismatches and misses the seed
// peer cache, silently falling back to origin fetch:
//
//	bucket, basePath := parse(mountPoint)          // oss://{bucket}/{basePath}
//	objectName       := join(basePath, attributes.Path)
//	remoteURL        := https://{bucket}.{ossEndpoint}/{objectName}
//
// attributes.Path looks like {sourcePodUID}/{version}/{containerName}/checkpoint
// and is the checkpoint **directory** (containing several independent parts
// like part-00.tar ...), no longer a single tar file; the controller probes
// the directory and creates a separate preheat task per part. version is the
// timestamp of the checkpoint start and cannot be derived, so it must be read
// from the CR status rather than computed.
func resolveSourceFromCheckpoint(ctx context.Context, c client.Client, job *v1beta1.PreheatJob) (*resolvedSource, error) {
	checkpointCR, err := findCheckpointByUID(ctx, c, job.Spec.CheckpointUID)
	if err != nil {
		return nil, err
	}

	// PVC-mode checkpoint: the preheat source is the PVC itself, resolving to
	// the three pvc fields (path taken from the checkpoint relative path pinned
	// in status); remoteURL is generated by the caller.
	if checkpointCR.Spec.StorageType == storageTypePVC {
		return resolvePVCSourceFromCheckpoint(checkpointCR)
	}

	mountPoint, endpoint, options, err := ossCoordinates(checkpointCR)
	if err != nil {
		return nil, err
	}

	objectPath, err := checkpointObjectPath(checkpointCR)
	if err != nil {
		return nil, err
	}

	remoteURL, err := buildRemoteURL(mountPoint, endpoint, objectPath)
	if err != nil {
		return nil, err
	}

	return &resolvedSource{
		remoteURL:       remoteURL,
		accessKeyID:     options[OptionAccessKeyID],
		accessKeySecret: options[OptionAccessKeySecret],
	}, nil
}

// resolvePVCSourceFromCheckpoint resolves pvcName/pvcNamespace and the
// in-PVC relative path of the checkpoint directory from a storageType=pvc
// checkpoint CR.
func resolvePVCSourceFromCheckpoint(cr *v1beta1.ContainerStateMigrationJobRequest) (*resolvedSource, error) {
	storage := cr.Spec.Storage
	if storage == nil || storage.PVC == nil {
		return nil, fmt.Errorf("checkpoint CR %s/%s has storageType=pvc but no spec.storage.pvc",
			cr.Namespace, cr.Name)
	}
	if storage.PVC.PvcName == "" || storage.PVC.PvcNamespace == "" {
		return nil, fmt.Errorf("checkpoint CR %s/%s has empty pvcName or pvcNamespace in spec.storage.pvc",
			cr.Namespace, cr.Name)
	}

	objectPath, checkpointSize, err := checkpointObjectPathAndSize(cr)
	if err != nil {
		return nil, err
	}

	return &resolvedSource{
		pvcName:        storage.PVC.PvcName,
		pvcNamespace:   storage.PVC.PvcNamespace,
		pvcPath:        objectPath,
		checkpointSize: checkpointSize,
	}, nil
}

// findCheckpointByUID finds the checkpoint CR by UID.
//
// K8s does not support a direct Get by UID; only a full List then compare,
// consistent with LookupCheckpointHandler. Preheat task creation is a one-shot
// action, so this cost is acceptable.
func findCheckpointByUID(ctx context.Context, c client.Client, uid string) (*v1beta1.ContainerStateMigrationJobRequest, error) {
	list := &v1beta1.ContainerStateMigrationJobRequestList{}
	if err := c.List(ctx, list); err != nil {
		return nil, fmt.Errorf("failed to list checkpoint CRs: %v", err)
	}
	for i := range list.Items {
		if string(list.Items[i].UID) == uid {
			return &list.Items[i], nil
		}
	}
	return nil, fmt.Errorf("checkpoint CR with UID %s not found", uid)
}

// ossCoordinates extracts the OSS mount point, endpoint and extra options from the checkpoint CR.
func ossCoordinates(cr *v1beta1.ContainerStateMigrationJobRequest) (mountPoint, endpoint string, options map[string]string, err error) {
	storage := cr.Spec.Storage
	if storage == nil {
		return "", "", nil, fmt.Errorf("checkpoint CR %s/%s has no spec.storage", cr.Namespace, cr.Name)
	}

	switch cr.Spec.StorageType {
	case storageTypeOSS:
		if storage.OSS == nil {
			return "", "", nil, fmt.Errorf("checkpoint CR %s/%s has storageType=oss but no spec.storage.oss", cr.Namespace, cr.Name)
		}
		return storage.OSS.MountPoint, storage.OSS.Endpoint, storage.OSS.Options, nil
	case storageTypeDragonfly:
		if storage.Dragonfly == nil {
			return "", "", nil, fmt.Errorf("checkpoint CR %s/%s has storageType=dragonfly but no spec.storage.dragonfly", cr.Namespace, cr.Name)
		}
		return storage.Dragonfly.OSSMountPoint, storage.Dragonfly.OSSEndpoint, storage.Dragonfly.Options, nil
	default:
		return "", "", nil, fmt.Errorf("checkpoint CR %s/%s storageType=%q cannot be resolved into a remote URL, only %s and %s are supported",
			cr.Namespace, cr.Name, cr.Spec.StorageType, storageTypeOSS, storageTypeDragonfly)
	}
}

// checkpointObjectPath extracts the container's object-relative path from the
// checkpoint CR's status.
//
// Checkpoints currently dump only a single container and one PreheatJob maps
// to exactly one object, so there must be exactly one container with a data
// path in the checkpoint result; with multiple it cannot auto-decide which to
// preheat, so error out and list the container names.
func checkpointObjectPath(cr *v1beta1.ContainerStateMigrationJobRequest) (string, error) {
	objectPath, _, err := checkpointObjectPathAndSize(cr)
	return objectPath, err
}

// checkpointObjectPathAndSize returns both the object-relative path and the total checkpoint data size.
func checkpointObjectPathAndSize(cr *v1beta1.ContainerStateMigrationJobRequest) (string, int64, error) {
	if cr.Status.CheckpointStatus == nil {
		return "", 0, fmt.Errorf("checkpoint CR %s/%s has no status.checkpointStatus yet, checkpoint data path is not available",
			cr.Namespace, cr.Name)
	}

	type containerData struct {
		path string
		size int64
	}
	datas := map[string]containerData{}
	names := make([]string, 0, len(cr.Status.CheckpointStatus.ContainerMigrationStatuses))
	for i := range cr.Status.CheckpointStatus.ContainerMigrationStatuses {
		cms := &cr.Status.CheckpointStatus.ContainerMigrationStatuses[i]
		if cms.CheckpointAttributes == nil || cms.CheckpointAttributes.Path == "" {
			continue
		}
		datas[cms.Name] = containerData{path: cms.CheckpointAttributes.Path, size: cms.CheckpointAttributes.Size}
		names = append(names, cms.Name)
	}
	sort.Strings(names)

	switch len(names) {
	case 0:
		return "", 0, fmt.Errorf("checkpoint CR %s/%s has no checkpoint data path in status (phase=%s), the checkpoint may not have finished yet",
			cr.Namespace, cr.Name, cr.Status.CheckpointStatus.Phase)
	case 1:
		data := datas[names[0]]
		return data.path, data.size, nil
	default:
		return "", 0, fmt.Errorf("checkpoint CR %s/%s contains %d containers with checkpoint data (%s), preheat only supports single-container checkpoints",
			cr.Namespace, cr.Name, len(names), formatNames(names))
	}
}

// buildRemoteURL composes the OSS mount point, endpoint and object-relative path into an http(s) address.
func buildRemoteURL(mountPoint, endpoint, objectPath string) (string, error) {
	if mountPoint == "" {
		return "", fmt.Errorf("oss mountPoint is empty in checkpoint CR storage")
	}
	if endpoint == "" {
		return "", fmt.Errorf("oss endpoint is empty in checkpoint CR storage")
	}

	// The mount point looks like oss://{bucket}/{basePath}.
	u, err := url.Parse(mountPoint)
	if err != nil {
		return "", fmt.Errorf("invalid oss mountPoint %q: %v", mountPoint, err)
	}
	if u.Scheme != "oss" {
		return "", fmt.Errorf("invalid oss mountPoint %q: want scheme oss://", mountPoint)
	}
	bucket := u.Host
	if bucket == "" {
		return "", fmt.Errorf("invalid oss mountPoint %q: bucket is empty", mountPoint)
	}

	objectName := strings.TrimPrefix(path.Join(u.Path, objectPath), "/")
	if objectName == "" {
		return "", fmt.Errorf("resolved object name is empty for mountPoint %q", mountPoint)
	}

	return fmt.Sprintf("https://%s.%s/%s", bucket, endpoint, objectName), nil
}

// formatNames joins the container name list into a readable string; an empty list returns "none".
func formatNames(names []string) string {
	if len(names) == 0 {
		return "none"
	}
	return strings.Join(names, ", ")
}
