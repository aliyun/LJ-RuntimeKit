package controller

import (
	"fmt"
	"strings"
	"testing"
)

func TestBuildJobName(t *testing.T) {
	tests := []struct {
		name     string
		nodeName string
		action   string
	}{
		{"short node", "node-1", JobActionEnable},
		{"e2e node", "t09c06224.cloud.sqa.na131", JobActionDisable},
		{"long node enable", "amp-vgpu-runtime011161226048.na132", JobActionEnable},
		{"long node disable", "amp-vgpu-runtime011161226048.na132", JobActionDisable},
		{"very long node", strings.Repeat("n", 80) + ".example.com", JobActionDisable},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := buildJobName(tt.nodeName, tt.action)

			if len(got) > maxJobNameLen {
				t.Errorf("job name too long: len=%d, name=%q", len(got), got)
			}
			if !strings.HasPrefix(got, jobNamePrefix) {
				t.Errorf("job name missing prefix: %q", got)
			}
			if !strings.HasSuffix(got, "-"+tt.action) {
				t.Errorf("job name missing action suffix %q: %q", tt.action, got)
			}
		})
	}
}

// TestBuildJobNameUniqueness ensures two long node names sharing the same
// truncated part still produce distinct job names via the hash.
func TestBuildJobNameUniqueness(t *testing.T) {
	base := strings.Repeat("a", 50)
	n1 := buildJobName(base+"node1", JobActionEnable)
	n2 := buildJobName(base+"node2", JobActionEnable)
	if n1 == n2 {
		t.Errorf("expected unique job names for different nodes, both were %q", n1)
	}
}

// TestBuildJobNameSequentialNodes simulates a 10k-node fleet with
// sequentially numbered long node names whose truncated prefixes are
// identical, verifying that the hash keeps job names unique across the batch.
func TestBuildJobNameSequentialNodes(t *testing.T) {
	seen := make(map[string]string)
	for i := 0; i < 10000; i++ {
		// 52-char node names: long enough to trigger truncation, and the
		// varying sequence number falls outside the truncated part.
		node := fmt.Sprintf("amp-vgpu-runtime011161226048-%05d.na132.example.com", i)
		name := buildJobName(node, JobActionDisable)
		if prev, ok := seen[name]; ok {
			t.Fatalf("job name collision: %q generated by both %q and %q", name, prev, node)
		}
		seen[name] = node
	}
}
