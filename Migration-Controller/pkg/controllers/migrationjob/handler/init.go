// InitHandler initializes the migration task.
type InitHandler struct {
	sharedContext *controllers.SharedContext
}

var _ = (controllers.Handler[*v1beta1.ContainerStateMigrationJobRequest])(&InitHandler{})

func NewInitHandler(sharedContext *controllers.SharedContext) *InitHandler {
	return &InitHandler{sharedContext: sharedContext}
}

func (h *InitHandler) GetName() string {
	return "InitHandler"
}

func (h *InitHandler) Handle(ctx context.Context, jobReq *v1beta1.ContainerStateMigrationJobRequest) (result controllers.Result) {
	ctxLog := log.FromContext(ctx)
	// Boilerplate logs are emitted uniformly by controller.go; not repeated here.

	status := &jobReq.Status

	// Skip if already initialized, but the finalizer still needs to be added: CRs upgraded from old versions do not carry it.
	if status.Phase != "" {
		if err := h.ensureFinalizer(ctx, jobReq); err != nil {
			return controllers.NewErrorResult(err)
		}
		return controllers.NewSkipResult("already initialized (phase already set)")
	}

	// The finalizer must be attached before creating any node-side side
	// effects, otherwise a deletion in between would leave the data on both
	// nodes unreclaimable.
	if err := h.ensureFinalizer(ctx, jobReq); err != nil {
		return controllers.NewErrorResult(err)
	}

	spec := &jobReq.Spec

	// Validate: at least one of checkpoint / restore must be non-nil.
	if spec.Checkpoint == nil && spec.Restore == nil {
		status.Phase = v1beta1.JobPhaseFailed
		status.Message = "Validation failed: checkpoint and restore cannot both be nil"
		return controllers.NewDoneResult()
	}

	// Validate: replicas is required when restore is non-nil.
	if spec.Restore != nil && spec.Restore.Replicas <= 0 {
		status.Phase = v1beta1.JobPhaseFailed
		status.Message = "Validation failed: restore.replicas must be > 0"
		return controllers.NewDoneResult()
	}

	// Validate: checkpointUID is required in restore-only mode.
	if spec.Checkpoint == nil && spec.Restore != nil && spec.Restore.CheckpointUID == "" {
		status.Phase = v1beta1.JobPhaseFailed
		status.Message = "Validation failed: restore.checkpointUID is required when checkpoint is nil"
		return controllers.NewDoneResult()
	}

	// Validate: storage is required. Under the current design both checkpoint
	// artifacts and restore pulls go through the storage backend; without it
	// the worker cannot locate the data - better to stop at the entry than fail
	// at dispatch.
	if spec.Storage == nil {
		status.Phase = v1beta1.JobPhaseFailed
		status.Message = "Validation failed: storage is required"
		return controllers.NewDoneResult()
	}

	// Validate: the storage content must match storageType and all required fields must be present.
	//
	// The CR may be auto-generated by the pod controller from an annotation;
	// that side deliberately does not intercept (as long as the switch is true
	// a CR is always written, otherwise the user is left with only an expiring
	// Event), so this is the only place where field errors are written back
	// into status.message.
	if msg := validateStorage(spec); msg != "" {
		status.Phase = v1beta1.JobPhaseFailed
		status.Message = "Validation failed: " + msg
		return controllers.NewDoneResult()
	}

	// Validate: PVC mode must reference an existing PVC. The accessMode
	// semantics are phased: tasks with a restore stage (restore-only or
	// checkpoint+restore dual-stage) require RWX; pure checkpoint tasks accept
	// RWO or RWX (status and events are written inside validatePVCOnInit).
	if res := h.validatePVCOnInit(ctx, jobReq); res.IsDone() {
		return res
	} else if res.IsError() {
		// Transient read failure: retry, do not judge the task dead.
		return res
	}

	// Validate: the checkpoint container list must have exactly one container.
	// containers stays a list type to reserve room for future multi-container
	// support, but worker / XDM are currently single-container only; filling
	// zero (the old behavior would default to all containers) or more than one
	// yields unpredictable results, so it is stopped at the entry.
	if spec.Checkpoint != nil && len(spec.Checkpoint.Containers) != 1 {
		status.Phase = v1beta1.JobPhaseFailed
		status.Message = fmt.Sprintf(
			"Validation failed: checkpoint.containers must contain exactly one container, got %d",
			len(spec.Checkpoint.Containers))
		return controllers.NewDoneResult()
	}

	// Validate: the checkpoint timeout / auto-mode combination. Illegal values
	// and blocked combinations are written back to status.message here; the
	// checkpoint stage must not run for them.
	if spec.Checkpoint != nil {
		if msg := validateCheckpointTimeout(spec.Checkpoint, jobReq.Annotations); msg != "" {
			status.Phase = v1beta1.JobPhaseFailed
			status.Message = msg
			return controllers.NewDoneResult()
		}
	}

	// Initialize.
	// Restore-only mode enters the Restoring phase directly, skipping checkpoint.
	if spec.Checkpoint == nil && spec.Restore != nil {
		status.Phase = v1beta1.JobPhaseRestoring
	} else {
		status.Phase = v1beta1.JobPhasePending
	}
	status.RequestID = util.GenerateUUID().String()

	// Checkpoint mode: initialize checkpointStatus and look up the source pod.
	if spec.Checkpoint != nil {
		checkpointSpec := spec.Checkpoint

		// Look up the source pod.
		pod := &corev1.Pod{}
		err := h.sharedContext.Client.Get(ctx, client.ObjectKey{
			Namespace: checkpointSpec.SourcePodNamespace,
			Name:      checkpointSpec.SourcePodName,
		}, pod)
		if err != nil && !errors.IsNotFound(err) {
			ctxLog.Error(err, "Failed to get source pod",
				"pod", fmt.Sprintf("%s/%s", checkpointSpec.SourcePodNamespace, checkpointSpec.SourcePodName))
			return controllers.NewErrorResult(err)
		}
		if errors.IsNotFound(err) || string(pod.UID) != checkpointSpec.SourcePodUID {
			status.Phase = v1beta1.JobPhaseFailed
			status.Message = fmt.Sprintf("Source pod %s/%s not found or UID mismatch", checkpointSpec.SourcePodNamespace, checkpointSpec.SourcePodName)
			return controllers.NewDoneResult()
		}

		// Determine the containers to checkpoint: validated above to be exactly
		// one, and it must actually exist in the source pod, otherwise
		// ContainerMigrationStatuses would be empty and the task would run all
		// the way to the worker before failing with an obscure error.
		containerNames := sets.NewString(checkpointSpec.Containers...)
		podContainerNames := sets.NewString()
		for _, c := range pod.Spec.Containers {
			podContainerNames.Insert(c.Name)
		}
		if unknown := containerNames.Difference(podContainerNames); unknown.Len() > 0 {
			status.Phase = v1beta1.JobPhaseFailed
			status.Message = fmt.Sprintf("Validation failed: checkpoint.containers %s not found in source pod %s/%s",
				strings.Join(unknown.List(), ","), checkpointSpec.SourcePodNamespace, checkpointSpec.SourcePodName)
			return controllers.NewDoneResult()
		}

		// Check whether the container is running.
		if !util.IsPodContainersRunning(pod, containerNames.List()...) {
			status.Phase = v1beta1.JobPhaseFailed
			status.Message = "Source pod containers not all running"
			return controllers.NewDoneResult()
		}

		// Initialize checkpointStatus.
		status.CheckpointStatus = &v1beta1.JobCheckpointStatus{
			Phase: v1beta1.JobPhasePending,
			// SourcePodTemplate must be pinned here: by restore time the source
			// pod may already be deleted, while the target pod needs the source
			// pod's original image and config to rebuild. Its ObjectMeta also
			// carries the source pod's identity (name / namespace / labels /
			// annotations), read directly in the restore stage.
			SourcePodTemplate: buildSourcePodTemplate(pod),
		}

		// Initialize the migration status of each container.
		for i := range pod.Status.ContainerStatuses {
			cs := pod.Status.ContainerStatuses[i]
			if containerNames.Has(cs.Name) {
				status.CheckpointStatus.ContainerMigrationStatuses = append(
					status.CheckpointStatus.ContainerMigrationStatuses,
					v1beta1.ContainerMigrationStatus{
						Name:        cs.Name,
						ContainerID: cs.ContainerID,
						Conditions:  make([]metav1.Condition, 0),
					},
				)
			}
		}
	}

	// Restore mode: initialize restoreStatus.
	if spec.Restore != nil {
		status.RestoreStatus = &v1beta1.JobRestoreStatus{
			Phase: v1beta1.JobPhasePending,
		}
	}

	return controllers.NewAbortWithRetryAfterResult(h.sharedContext.Config.RetryWaitTime)
}

// validateStorage validates that spec.storage matches spec.storageType and
// all required fields are present, returning an empty string on pass. The
// caller guarantees spec.Storage is non-nil.
//
// The required fields follow the minimum the worker needs to locate data:
// missing them guarantees the task fails after dispatch; better to write it
// into status.message here than make the user dig through worker logs.
func validateStorage(spec *v1beta1.ContainerStateMigrationJobRequestSpec) string {
	storage := spec.Storage

	switch spec.StorageType {
	case v1beta1.StorageTypeLocal, v1beta1.StorageTypeNFS,
		v1beta1.StorageTypeOSS, v1beta1.StorageTypeDragonfly, v1beta1.StorageTypeEFC,
		v1beta1.StorageTypePVC:
	default:
		return fmt.Sprintf("storageType %q is not supported, expect one of %s/%s/%s/%s/%s/%s",
			spec.StorageType, v1beta1.StorageTypeLocal, v1beta1.StorageTypeNFS,
			v1beta1.StorageTypeOSS, v1beta1.StorageTypeDragonfly, v1beta1.StorageTypeEFC,
			v1beta1.StorageTypePVC)
	}

	// Only the backend matching storageType may be declared. At dispatch,
	// convertJobStorageToGrpcStorage takes the first non-nil backend in the
	// order local -> nfs -> oss -> dragonfly -> efc -> pvc, regardless of
	// storageType; while the worker picks its plugin by storageType. When the
	// two disagree the worker gets an empty backend config and the reported
	// error is unrelated to the real cause, so it is stopped at the entry.
	if extra := backendsOtherThan(spec.StorageType, storage); len(extra) > 0 {
		return fmt.Sprintf("storageType is %q but storage also declares %s, only the matching backend may be set",
			spec.StorageType, strings.Join(extra, ", "))
	}

	switch spec.StorageType {
	case v1beta1.StorageTypeLocal:
		if storage.Local == nil || strings.TrimSpace(storage.Local.Path) == "" {
			return "storage.local.path is required when storageType is local"
		}
		if !strings.HasPrefix(storage.Local.Path, "/") {
			return fmt.Sprintf("storage.local.path must be an absolute path, got %q", storage.Local.Path)
		}

	case v1beta1.StorageTypeNFS:
		if storage.NFS == nil {
			return "storage.nfs is required when storageType is nfs"
		}
		if missing := missingFields(
			"storage.nfs.server", storage.NFS.Server,
			"storage.nfs.path", storage.NFS.Path,
		); len(missing) > 0 {
			return fmt.Sprintf("missing required fields: %s", strings.Join(missing, ", "))
		}

	case v1beta1.StorageTypeOSS:
		if storage.OSS == nil {
			return "storage.oss is required when storageType is oss"
		}
		if missing := missingFields(
			"storage.oss.endpoint", storage.OSS.Endpoint,
			"storage.oss.mountPoint", storage.OSS.MountPoint,
		); len(missing) > 0 {
			return fmt.Sprintf("missing required fields: %s", strings.Join(missing, ", "))
		}
		return missingOSSCredentials("storage.oss.options", storage.OSS.Options)

	case v1beta1.StorageTypeDragonfly:
		if storage.Dragonfly == nil {
			return "storage.dragonfly is required when storageType is dragonfly"
		}
		if missing := missingFields(
			"storage.dragonfly.ossEndpoint", storage.Dragonfly.OSSEndpoint,
			"storage.dragonfly.ossMountPoint", storage.Dragonfly.OSSMountPoint,
		); len(missing) > 0 {
			return fmt.Sprintf("missing required fields: %s", strings.Join(missing, ", "))
		}
		// When a PreheatJob is enabled, credentials are taken from the
		// PreheatJob's spec.options (see the worker-side storage/preheatjob.go);
		// not writing credentials in storage.dragonfly.options is legal then.
		if storage.Dragonfly.PreheatJobName == "" {
			return missingOSSCredentials("storage.dragonfly.options", storage.Dragonfly.Options)
		}

	case v1beta1.StorageTypeEFC:
		if storage.EFC == nil {
			return "storage.efc is required when storageType is efc"
		}
		// Mounting and origin fetching are entirely handled by the node-side
		// runtimekit; the only data location the controller must tell it is the
		// bucket - without it the worker cannot locate the checkpoint.
		if missing := missingFields(
			"storage.efc.bucketName", storage.EFC.BucketName,
		); len(missing) > 0 {
			return fmt.Sprintf("missing required fields: %s", strings.Join(missing, ", "))
		}

	case v1beta1.StorageTypePVC:
		if storage.PVC == nil {
			return "storage.pvc is required when storageType is pvc"
		}
		if missing := missingFields(
			"storage.pvc.pvcName", storage.PVC.PvcName,
			"storage.pvc.pvcNamespace", storage.PVC.PvcNamespace,
		); len(missing) > 0 {
			return fmt.Sprintf("missing required fields: %s", strings.Join(missing, ", "))
		}
	}
	return ""
}

// checkpointAutoModeWarnings are the two warnings written back to
// status.message when the checkpoint stage must not run. Kept verbatim as
// agreed with the user - do not reword.
const (
	// checkpointAutoModeWarningExplicitZero: auto-created CR whose
	// checkpoint-timeout-minutes is an explicit 0 - checkpointing a
	// just-started model-serving pod is unreasonable.
	checkpointAutoModeWarningExplicitZero = "Checkpointing a model-serving pod that has just been started is unreasonable. Please explicitly specify a positive integer for checkpoint-timeout-minutes; or, without explicitly setting checkpoint-timeout-minutes, enable checkpoint-automode-enable so that the system can automatically detect the steady-state point of the model service and trigger a checkpoint."
	// checkpointAutoModeWarningNoTimeout: auto mode explicitly off while no
	// timeout is specified at all - there is no trigger for the checkpoint.
	checkpointAutoModeWarningNoTimeout = "When checkpoint-automode-enable is not enabled, checkpoint-timeout-minutes must be explicitly specified, and it is used to trigger the checkpoint action at the appropriate time."
)

// validateCheckpointTimeout validates the checkpoint timeout / auto-mode
// combination, returning an empty string on pass.
//
// Rules, in order:
//  1. an explicit negative timeoutInMinute is rejected;
//  2. illegal raw annotation values carried over from the pod-annotation
//     path (non-integer timeout, non-boolean automode) are rejected;
//  3. on an auto-created CR an explicit 0 timeout blocks the checkpoint with
//     the first warning (a just-started model-serving pod must not be
//     checkpointed right away);
//  4. auto mode explicitly off with no timeout at all blocks the checkpoint
//     with the second warning.
//
// CRD-authored CRs (not auto-created) keep the old semantics for an explicit
// 0: it is passed through to cr-tool as --timeout 0.
func validateCheckpointTimeout(checkpoint *v1beta1.CheckpointSpec, annotations map[string]string) string {
	if checkpoint.TimeoutInMinute != nil && *checkpoint.TimeoutInMinute < 0 {
		return fmt.Sprintf("Validation failed: checkpoint.timeoutInMinute must be a non-negative integer, got %d",
			*checkpoint.TimeoutInMinute)
	}
	if raw, ok := annotations[labels.AnnotationAutoCheckpointInvalidTimeout]; ok {
		return fmt.Sprintf("Validation failed: annotation %s must be a non-negative integer, got %q",
			labels.AnnotationCheckpointTimeoutMinutes, raw)
	}
	if raw, ok := annotations[labels.AnnotationAutoCheckpointInvalidAutoMode]; ok {
		return fmt.Sprintf("Validation failed: annotation %s must be true or false, got %q",
			labels.AnnotationCheckpointAutoModeEnable, raw)
	}
	if annotations[labels.AnnotationAutoCreated] == "true" &&
		checkpoint.TimeoutInMinute != nil && *checkpoint.TimeoutInMinute == 0 {
		return checkpointAutoModeWarningExplicitZero
	}
	if checkpoint.EnableCheckpointAutoMode != nil && !*checkpoint.EnableCheckpointAutoMode &&
		checkpoint.TimeoutInMinute == nil {
		return checkpointAutoModeWarningNoTimeout
	}
	return ""
}

// backendsOtherThan returns the backends declared in storage beyond the one storageType points to.
func backendsOtherThan(storageType string, storage *v1beta1.JobStorage) []string {
	extra := make([]string, 0, 5)
	if storage.Local != nil && storageType != v1beta1.StorageTypeLocal {
		extra = append(extra, "storage.local")
	}
	if storage.NFS != nil && storageType != v1beta1.StorageTypeNFS {
		extra = append(extra, "storage.nfs")
	}
	if storage.OSS != nil && storageType != v1beta1.StorageTypeOSS {
		extra = append(extra, "storage.oss")
	}
	if storage.Dragonfly != nil && storageType != v1beta1.StorageTypeDragonfly {
		extra = append(extra, "storage.dragonfly")
	}
	if storage.EFC != nil && storageType != v1beta1.StorageTypeEFC {
		extra = append(extra, "storage.efc")
	}
	if storage.PVC != nil && storageType != v1beta1.StorageTypePVC {
		extra = append(extra, "storage.pvc")
	}
	return extra
}

// missingFields takes names and values alternately and picks out the names
// whose value is empty, in order. A map is deliberately avoided to keep the
// error message order stable; otherwise status.message would change shape every
// time.
func missingFields(nameValues ...string) []string {
	missing := make([]string, 0, len(nameValues)/2)
	for i := 0; i+1 < len(nameValues); i += 2 {
		if strings.TrimSpace(nameValues[i+1]) == "" {
			missing = append(missing, nameValues[i])
		}
	}
	return missing
}

// missingOSSCredentials validates that the OSS credential keys are complete,
// returning an empty string on pass. Key names are case-sensitive and must
// match the Migration-Worker side.
func missingOSSCredentials(field string, options map[string]string) string {
	for _, key := range []string{labels.OSSAccessKeyID, labels.OSSAccessKeySecret} {
		if strings.TrimSpace(options[key]) == "" {
			return fmt.Sprintf("%s must contain a non-empty %s", field, key)
		}
	}
	return ""
}

// ensureFinalizer idempotently attaches the cleanup finalizer to the CR.
func (h *InitHandler) ensureFinalizer(ctx context.Context,
	jobReq *v1beta1.ContainerStateMigrationJobRequest) error {
	if controllerutil.ContainsFinalizer(jobReq, MigrationJobFinalizer) {
		return nil
	}
	controllerutil.AddFinalizer(jobReq, MigrationJobFinalizer)
	if err := h.sharedContext.Client.Update(ctx, jobReq); err != nil {
		log.FromContext(ctx).Error(err, "Failed to add cleanup finalizer")
		return err
	}
	return nil
}

// buildSourcePodTemplate extracts the source pod into a reproducible
// template: scheduling results and node-related fields are cleared, and the
// ServiceAccount token projected volumes auto-injected by kubelet are removed
// (they would be re-injected on the new pod anyway, copying them would only
// conflict).
func buildSourcePodTemplate(pod *corev1.Pod) *corev1.PodTemplateSpec {
	if pod == nil {
		return nil
	}
	template := &corev1.PodTemplateSpec{
		ObjectMeta: metav1.ObjectMeta{
			// Name / Namespace / Labels / Annotations are the source pod's
			// identity; the restore stage reads all of them here when building
			// the target pod. SourcePodTemplate is stored with Schemaless +
			// PreserveUnknownFields, so this metadata is not pruned by the
			// apiserver.
			Name:        pod.Name,
			Namespace:   pod.Namespace,
			UID:         pod.UID,
			Labels:      copyStringMap(pod.Labels),
			Annotations: copyStringMap(pod.Annotations),
		},
		Spec: *pod.Spec.DeepCopy(),
	}
	template.Spec.NodeName = ""
	template.Spec.Hostname = ""
	filterServiceAccountMounts(&template.Spec)
	return template
}

// filterServiceAccountMounts removes the kube-api-access-* style volumes
// auto-injected by kubelet and the corresponding VolumeMounts on each
// container.
func filterServiceAccountMounts(spec *corev1.PodSpec) {
	removed := sets.NewString()
	volumes := make([]corev1.Volume, 0, len(spec.Volumes))
	for i := range spec.Volumes {
		if strings.HasPrefix(spec.Volumes[i].Name, "kube-api-access-") {
			removed.Insert(spec.Volumes[i].Name)
			continue
		}
		volumes = append(volumes, spec.Volumes[i])
	}
	if removed.Len() == 0 {
		return
	}
	spec.Volumes = volumes

	dropMounts := func(containers []corev1.Container) {
		for i := range containers {
			mounts := make([]corev1.VolumeMount, 0, len(containers[i].VolumeMounts))
			for j := range containers[i].VolumeMounts {
				if removed.Has(containers[i].VolumeMounts[j].Name) {
					continue
				}
				mounts = append(mounts, containers[i].VolumeMounts[j])
			}
			containers[i].VolumeMounts = mounts
		}
	}
	dropMounts(spec.Containers)
	dropMounts(spec.InitContainers)
}
